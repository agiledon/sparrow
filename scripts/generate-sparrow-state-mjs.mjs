#!/usr/bin/env node
/**
 * Bundle src/agent-scripts/sparrow-state.ts → templates/shared/scripts/sparrow-state.mjs
 * so agent-facing scripts share one implementation with src/core/project-state.ts.
 */
import * as esbuild from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src/agent-scripts/sparrow-state.ts');
const outfile = join(root, 'src/schemas/templates/shared/scripts/sparrow-state.mjs');

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'esm',
  write: false,
  logLevel: 'silent',
});

const code = result.outputFiles?.[0]?.text;
if (!code) {
  console.error('esbuild produced no output for sparrow-state.mjs');
  process.exit(1);
}

const banner =
  '#!/usr/bin/env node\n' +
  '/**\n' +
  ' * AUTO-GENERATED by scripts/generate-sparrow-state-mjs.mjs — do not edit by hand.\n' +
  ' * Source: src/agent-scripts/sparrow-state.ts (+ src/core/project-state.ts).\n' +
  ' * Re-run: node scripts/generate-sparrow-state-mjs.mjs (also via npm run sync-schema).\n' +
  ' */\n';

writeFileSync(outfile, banner + code, 'utf-8');
console.log('generated', outfile.replace(root + '/', ''));
