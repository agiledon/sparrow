#!/usr/bin/env node
/**
 * Generate src/schemas/bundled-content.ts from templates, workflow-blocks, and harness files.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemas = join(root, 'src', 'schemas');
const templates = join(schemas, 'templates');

function walk(dir) {
  const out = [];
  if (!existsSync(dir) || !statSync(dir).isDirectory()) return out;
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

function importId(rel) {
  return `_${rel.replace(/[^a-zA-Z0-9]/g, '_')}`;
}

function posixRel(from, file) {
  return relative(from, file).split('\\').join('/');
}

const lines = [];
const emit = (s = '') => lines.push(s);

emit('/** Auto-generated by scripts/sync-bundled-content.mjs — do not edit by hand. */');
emit('');

emit(`import specLayoutGuideMd from './templates/shared/spec-layout-guide.md';`);
emit(`export const specLayoutGuide = specLayoutGuideMd;`);
emit('');

const sharedDir = join(templates, 'shared');
const sharedRefs = [];
const sharedAssets = [];
for (const file of walk(sharedDir)) {
  const relFromShared = posixRel(sharedDir, file);
  const id = importId(`shared/${relFromShared}`);
  emit(`import ${id} from './templates/shared/${relFromShared}';`);
  if (relFromShared.startsWith('assets/')) {
    sharedAssets.push([relFromShared.slice('assets/'.length), id]);
  } else {
    sharedRefs.push([relFromShared, id]);
  }
}
emit('');
emit('export const sharedReferences: Record<string, string> = {');
for (const [name, id] of sharedRefs) emit(`  '${name}': ${id},`);
emit('};');
emit('');
emit('export const sharedAssets: Record<string, string> = {');
for (const [name, id] of sharedAssets) emit(`  '${name}': ${id},`);
emit('};');
emit('');

const skillsDir = join(templates, 'skills');
const skillTemplates = [];
/** @type {Record<string, Array<[string, string]>>} */
const extras = {};

for (const skillName of readdirSync(skillsDir).sort()) {
  const skillPath = join(skillsDir, skillName);
  if (!statSync(skillPath).isDirectory()) continue;
  extras[skillName] = [];
  for (const file of walk(skillPath)) {
    const rel = posixRel(skillPath, file);
    const id = importId(`skill/${skillName}/${rel}`);
    emit(`import ${id} from './templates/skills/${skillName}/${rel}';`);
    if (rel === 'SKILL.md') {
      skillTemplates.push([`${skillName}/SKILL.md`, id]);
    } else {
      extras[skillName].push([rel, id]);
    }
  }
}
emit('');
emit('export const skillTemplates: Record<string, string> = {');
for (const [key, id] of skillTemplates) emit(`  '${key}': ${id},`);
emit('};');
emit('');
emit('export const skillExtras: Record<string, Record<string, string>> = {');
for (const [skillName, files] of Object.entries(extras)) {
  emit(`  '${skillName}': {`);
  for (const [rel, id] of files) emit(`    '${rel}': ${id},`);
  emit('  },');
}
emit('};');
emit('');

const wfDir = join(schemas, 'workflow-blocks');
const wf = [];
for (const file of walk(wfDir)) {
  if (!file.endsWith('.md')) continue;
  const name = posixRel(wfDir, file);
  const id = importId(`wf/${name}`);
  emit(`import ${id} from './workflow-blocks/${name}';`);
  wf.push([name, id]);
}
emit('');
emit('export const workflowBlocks: Record<string, string> = {');
for (const [name, id] of wf) emit(`  '${name}': ${id},`);
emit('};');
emit('');

const harnessDir = join(templates, 'harness');
const harness = [];
for (const file of walk(harnessDir)) {
  const rel = posixRel(harnessDir, file);
  const id = importId(`h/${rel}`);
  emit(`import ${id} from './templates/harness/${rel}';`);
  const text = readFileSync(file, 'utf8');
  const heading = text.match(/^#\s+(.+)$/m)?.[1]?.trim() || rel;
  harness.push([rel, heading, id]);
}
emit('');
emit('export interface BundledHarnessEntry { relPath: string; title: string; body: string; }');
emit('');
emit('export const bundledHarnessBodies: Record<string, { title: string; body: string }> = {');
for (const [rel, title, id] of harness) {
  emit(`  '${rel}': { title: ${JSON.stringify(title)}, body: ${id} },`);
}
emit('};');
emit('');

writeFileSync(join(schemas, 'bundled-content.ts'), lines.join('\n') + '\n');
console.log('synced bundled-content.ts');
