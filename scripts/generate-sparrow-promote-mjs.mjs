#!/usr/bin/env node
/**
 * Bundle src/agent-scripts/sparrow-promote.ts → templates/shared/scripts/sparrow-promote.mjs
 */
import * as esbuild from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src/agent-scripts/sparrow-promote.ts');
const outfile = join(root, 'src/content/workflows/_shared/scripts/sparrow-promote.mjs');

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'esm',
  write: false,
  logLevel: 'silent',
  // .md assets imported via bundled-content text loader path — pull skillExtras
  packages: 'bundle',
  loader: {
    '.md': 'text',
    '.yaml': 'text',
    '.html': 'text',
    '.mjs': 'text',
  },
});

const code = result.outputFiles?.[0]?.text;
if (!code) {
  console.error('esbuild produced no output for sparrow-promote.mjs');
  process.exit(1);
}

const banner =
  '#!/usr/bin/env node\n' +
  '/**\n' +
  ' * AUTO-GENERATED by scripts/generate-sparrow-promote-mjs.mjs — do not edit by hand.\n' +
  ' * Source: src/agent-scripts/sparrow-promote.ts (+ src/kernel/runtime/spec-promote.ts).\n' +
  ' * Re-run: node scripts/generate-sparrow-promote-mjs.mjs (also via npm run sync-schema).\n' +
  ' */\n';

writeFileSync(outfile, banner + code, 'utf-8');
console.log('generated', outfile.replace(root + '/', ''));
