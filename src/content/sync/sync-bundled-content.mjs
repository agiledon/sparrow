#!/usr/bin/env node
/**
 * Generate src/content/bundled-content.ts from content/harness and content/workflows.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const content = join(dirname(fileURLToPath(import.meta.url)), '..');
const workflowsDir = join(content, 'workflows');
const sharedDir = join(workflowsDir, '_shared');
const bundledOut = join(content, 'bundled-content.ts');
const importPrefix = '.';

function walk(dir) {
  const out = [];
  if (!existsSync(dir) || !statSync(dir).isDirectory()) return out;
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

function importId(rel) {
  return `_${rel.replace(/[^a-zA-Z0-9]/g, '_')}`;
}

function posixRel(from, file) {
  return relative(from, file).split('\\').join('/');
}

function contentImport(subpath) {
  return `${importPrefix}/${subpath}`;
}

const lines = [];
const emit = (s = '') => lines.push(s);

emit('/** Auto-generated by src/content/sync/sync-bundled-content.mjs — do not edit by hand. */');
emit('');

emit(`import specLayoutGuideMd from '${contentImport('workflows/_shared/spec-layout-guide.md')}';`);
emit(`export const specLayoutGuide = specLayoutGuideMd;`);
emit('');

const sharedRefs = [];
const sharedAssets = [];
const sharedScripts = [];
for (const file of walk(sharedDir)) {
  const relFromShared = posixRel(sharedDir, file);
  const id = importId(`shared/${relFromShared}`);
  emit(`import ${id} from '${contentImport(`workflows/_shared/${relFromShared}`)}';`);
  if (relFromShared.startsWith('assets/')) {
    sharedAssets.push([relFromShared.slice('assets/'.length), id]);
  } else if (relFromShared.startsWith('scripts/')) {
    sharedScripts.push([relFromShared.slice('scripts/'.length), id]);
  } else if (!relFromShared.endsWith('.md') && !relFromShared.endsWith('.mjs')) {
    continue;
  } else {
    sharedRefs.push([relFromShared, id]);
  }
}
emit('');
emit('export const sharedReferences: Record<string, string> = {');
for (const [name, id] of sharedRefs) emit(`  '${name}': ${id},`);
emit('};');
emit('');
emit('export const sharedAssets: Record<string, string> = {');
for (const [name, id] of sharedAssets) emit(`  '${name}': ${id},`);
emit('};');
emit('');
emit('export const sharedScripts: Record<string, string> = {');
for (const [name, id] of sharedScripts) emit(`  '${name}': ${id},`);
emit('};');
emit('');

const skillTemplates = [];
/** @type {Record<string, Array<[string, string]>>} */
const extras = {};
const wf = [];

for (const workflowId of readdirSync(workflowsDir).sort()) {
  if (workflowId === '_shared') continue;
  const wfPath = join(workflowsDir, workflowId);
  if (!statSync(wfPath).isDirectory()) continue;
  extras[workflowId] = [];

  for (const file of walk(wfPath)) {
    const rel = posixRel(wfPath, file);
    const id = importId(`wf/${workflowId}/${rel}`);
    emit(`import ${id} from '${contentImport(`workflows/${workflowId}/${rel}`)}';`);

    if (rel === 'activity.md') {
      skillTemplates.push([`${workflowId}/SKILL.md`, id]);
    } else if (rel === 'guideline.md') {
      wf.push([`${workflowId}.md`, id]);
    } else {
      extras[workflowId].push([rel, id]);
    }
  }
}

emit('');
emit('export const skillTemplates: Record<string, string> = {');
for (const [key, id] of skillTemplates) emit(`  '${key}': ${id},`);
emit('};');
emit('');
emit('export const skillExtras: Record<string, Record<string, string>> = {');
for (const [skillName, files] of Object.entries(extras)) {
  emit(`  '${skillName}': {`);
  for (const [rel, id] of files) emit(`    '${rel}': ${id},`);
  emit('  },');
}
emit('};');
emit('');
emit('export const workflowBlocks: Record<string, string> = {');
for (const [name, id] of wf) emit(`  '${name}': ${id},`);
emit('};');
emit('');

const harnessDir = join(content, 'harness');
const harness = [];
for (const file of walk(harnessDir)) {
  if (!file.endsWith('.md')) continue;
  const rel = posixRel(harnessDir, file);
  const id = importId(`h/${rel}`);
  emit(`import ${id} from '${contentImport(`harness/${rel}`)}';`);
  const text = readFileSync(file, 'utf8');
  const heading = text.match(/^#\s+(.+)$/m)?.[1]?.trim() || rel;
  harness.push([rel, heading, id]);
}
emit('');
emit('export interface BundledHarnessEntry { relPath: string; title: string; body: string; }');
emit('');
emit('export const bundledHarnessBodies: Record<string, { title: string; body: string }> = {');
for (const [rel, title, id] of harness) {
  emit(`  '${rel}': { title: ${JSON.stringify(title)}, body: ${id} },`);
}
emit('};');
emit('');

writeFileSync(bundledOut, lines.join('\n') + '\n');
console.log('synced bundled-content.ts');
